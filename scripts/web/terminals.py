#!/usr/bin/env python3
# Writes web/terminals.html: the terminals of the benchmark (foot, Alacritty, Ghostty, kitty) under Hypoland and stock
# Hyprland on every machine, one table per measure, from the same baseline as the lab page (labdata.py), so no number on
# the page is typed by hand. Run it again after a new baseline, from anywhere: scripts/web/terminals.py
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from labdata import ROOT, BASELINE, HYPRLAND, MACHINES, values, cell, E, head, FOOTER

OUT = os.path.join(ROOT, "web", "terminals.html")

# workload, name, version in the baseline's night, how it draws
TERMINALS = [
    ("terminal-scroll", "foot", "1.28.0", "On the CPU, into shared memory (wl_shm): the compositor makes the texture, by zero copy where it can."),
    ("alacritty-scroll", "Alacritty", "0.17.0", "OpenGL ES 2 / OpenGL 3.3, GPU buffers (dmabuf); runs on the X200 too."),
    ("ghostty-scroll", "Ghostty", "1.4.0", "A GTK 4 window drawn by Ghostty's own OpenGL 3.3 renderer, GPU buffers."),
    ("kitty-scroll", "kitty", "0.49.2", "OpenGL 3.3, GPU buffers."),
]

# key pattern ({w} is the workload), title, unit, whether lower is better, what it says
MEASURES = [
    ("cpu.{w}.percent", "The compositor's CPU", "%", True,
     "Percent of one core over the 12 s of scrolling: the compositor alone, all its threads."),
    ("cpu.{w}.ms_per_frame", "The compositor's CPU per frame on the screen", "ms/frame", True,
     "The same per frame the compositor put on the screen, so a compositor that shows more frames is not read as one "
     "that costs more."),
    ("fps.{w}.screen", "Frames on the screen", "fps", False,
     "The compositor's page flips a second. The terminals print as fast as they can, so this is how many of their frames "
     "reach the screen; the Galaxy Book's screen runs at 120&nbsp;Hz."),
]

FEW = 10
rows = [m for m in MACHINES if m["baseline"]]
data = {m["alias"]: (values(m["alias"], "hypoland"), values(m["alias"], "hyprland")) for m in rows}

def ran(v, w):
    # a terminal that did not start (Ghostty on Bay Trail and Ivy Bridge, which lack OpenGL 3.3) measures about 0
    c = v.get(f"cpu.{w}.clients_percent")
    return c is not None and c >= 1

def tables():
    out = []
    for i, (key, title, unit, lower, text) in enumerate(MEASURES):
        body = []
        for m in rows:
            (hv, hs), (sv, ss) = data[m["alias"]]
            cells = ""
            for w, *_ in TERMINALS:
                k = key.format(w=w)
                ok = ran(hv, w) and ran(sv, w)
                cells += cell(hv.get(k) if ok else None, sv.get(k) if ok else None, unit, lower)
            name = E(m["name"]) + (f" <span class=\"opt\">({min(hs, ss)} sessions)</span>" if min(hs, ss) < FEW else "")
            body.append(f"          <tr><td>{name}</td>{cells}</tr>")
        heads = "".join(f"<th>{E(n)}</th>" for _, n, _, _ in TERMINALS)
        out.append(f"""  <section class="win full" id="m{i + 1}" aria-labelledby="t-m{i + 1}">
    <h2 class="title" id="t-m{i + 1}">{E(title)}</h2>
    <div class="body">
      <div class="scroll"><table>
        <thead><tr><th>Hypoland / Hyprland {HYPRLAND}</th>{heads}</tr></thead>
        <tbody>
{chr(10).join(body)}
        </tbody>
      </table></div>
      <p class="note">{text}</p>
    </div>
  </section>
""")
    return "\n".join(out)

sessions = [min(data[m["alias"]][0][1], data[m["alias"]][1][1]) for m in rows]
full = [s for s in sessions if s >= FEW]
term_rows = "\n".join(f"          <tr><td>{E(n)}</td><td>{E(v)}</td><td>{E(d)}</td></tr>" for _, n, v, d in TERMINALS)
nav = "".join(f'\n    <li><a href="#m{i + 1}">{i + 2}</a></li>' for i in range(len(MEASURES)))

page = f"""{head("Hypoland: terminals", "foot, Alacritty, Ghostty and kitty scrolling under Hypoland and under Hyprland " + HYPRLAND + " on ten machines: the compositor's CPU and its frames.", "foot, Alacritty, Ghostty and kitty under Hypoland and Hyprland " + HYPRLAND + ", on ten machines.", "terminals.html")}
<!-- Generated by scripts/web/terminals.py from the baseline's values, do not edit by hand. -->
<nav class="bar" aria-label="Sections">
  <ul class="ws">
    <li><a class="on" href="#top">1</a></li>{nav}
  </ul>
  <div class="right">
    <span class="opt">terminals</span>
    <span><a href="index.html">home</a></span>
    <span><a href="lab.html">lab</a></span>
    <span><a href="https://github.com/hegjon/hypoland">github</a></span>
  </div>
</nav>

<main class="desk" id="top">

  <section class="win full" aria-labelledby="t-terminals">
    <h2 class="title" id="t-terminals">foot, Alacritty, Ghostty, kitty</h2>
    <div class="body">
      <p>
        Each terminal runs <code>while true; do ls -la /usr/lib; done</code> in a tiled window of Omarchy's session and
        scrolls as fast as it can for 12 seconds, on every machine of <a href="lab.html">the lab</a>, under Hypoland and
        under stock Hyprland {HYPRLAND}. Every cell is Hypoland / Hyprland: green where Hypoland is at least 5% better,
        red where it is at least 5% worse; a dash where the terminal does not run.
      </p>
      <div class="scroll"><table>
        <thead><tr><th>Terminal</th><th>Version</th><th>How it draws</th></tr></thead>
        <tbody>
{term_rows}
        </tbody>
      </table></div>
      <p class="note">
        Medians of {min(full)} to {max(full)} fresh sessions of each compositor per machine, alternating from 2026-11-03
        12:46 to 11-04 07:30 (Hypoland 0.3.0 against Hyprland {HYPRLAND}-4); the Galaxy Book has 2, its GPU hung early in the
        night. Ghostty and kitty need OpenGL&nbsp;3.3: not on the X200, and Ghostty does not start on the Chromebook and
        the Samsung (Bay Trail and Ivy Bridge). On the X200 Hyprland runs with Omarchy's GLES&nbsp;3 override
        (<a href="https://github.com/omacom/omarchy/pull/14764">omarchy#14764</a>), which the terminals get too.
        <a href="https://github.com/hegjon/hypoland/tree/master/{BASELINE}">Raw data, every session's values and the scripts</a>.
      </p>
    </div>
  </section>

{tables()}
</main>

{FOOTER}
"""
open(OUT, "w").write(page)
print(f"wrote {OUT}: {len(TERMINALS)} terminals, {len(MEASURES)} measures, {len(rows)} machines")

#!/usr/bin/env python3
# Writes web/lab.html, the page about the test machines: the hardware table (the facts below), and every machine's
# numbers against stock Hyprland, since 2026-11-25 the Hypoland 0.4.0 release against Hyprland 0.57.2 only (the runs and
# the machines are in labdata.py, with the history of the nights the page used before). No number on the page is typed
# by hand. Run it again after a new baseline, from anywhere: scripts/web/lab.py
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from labdata import ROOT, HYPRLAND, RUN, TWO_NIGHTS, RAW, MACHINES, RETIRED, values, sessions_text, cell, E, head, FOOTER, bar

OUT = os.path.join(ROOT, "web", "lab.html")
# machines left off this page (the user, 2026-11-21): the AMD A8-6600K desktop and the T550; the other pages keep them
HIDDEN = {"lianli", "t550"}
MACHINES = [m for m in MACHINES if m["alias"] not in HIDDEN]

# key in values.txt, label, unit, whether lower is better, scale
METRICS = [
    ("cpu.gpu-client.percent", "GPU client at 60 fps", "%", True, 1),
    ("cpu.terminal-scroll.percent", "foot terminal scrolling fast", "%", True, 1),
    ("cpu.shm-fullwindow.percent", "Chromium in a full window", "%", True, 1),
    ("cpu.workspace-switch.percent", "workspace switching", "%", True, 1),
    ("mem.start.Pss_kB", "memory (PSS), 60 s after the start", "MiB", True, 1 / 1024),
    ("fps.gtk3-scroll.screen", "frames on the screen, GTK 3 scrolling", "fps", False, 1),
    ("latency.workspace-switch.focus_ms", "a focus change shown", "ms", True, 1),
]

rows_hw = []
for m in MACHINES:
    rows_hw.append(f"          <tr><td>{E(m['name'])}</td><td>{m['year']}</td><td>{E(m['cpu'])}</td><td>{E(m['gpu'])}<br><code>{E(m['driver'])}</code></td>"
                   f"<td>{E(m['screen'])}</td><td>{E(m['ram'])}</td><td>{E(m['role'])}</td></tr>")

# cells left empty, no measurement of what the column means: on the Turbo-X's 1 GB Chromium never maps a window (its
# clients list is empty and 0 frames reach the screen in every session, under both compositors), and most of either
# compositor sits in swap, which PSS does not count (on 11-25 Hypoland had 5 MiB in RAM and 16.5 MiB in swap)
NO_CLIENT = {("turbox", "cpu.shm-fullwindow.percent"), ("turbox", "mem.start.Pss_kB")}

rows_num, sessions = [], {}
for m in MACHINES:
    if not m["baseline"]: continue
    hv, hs = values(m["alias"], "hypoland")
    sv, ss = values(m["alias"], "hyprland")
    sessions[m["alias"]] = (hs, ss)
    hv = {k: x for k, x in hv.items() if (m["alias"], k) not in NO_CLIENT}
    sv = {k: x for k, x in sv.items() if (m["alias"], k) not in NO_CLIENT}
    cells = "".join(cell(hv.get(k) * sc if hv.get(k) is not None else None, sv.get(k) * sc if sv.get(k) is not None else None, unit, lower)
                    for k, _, unit, lower, sc in METRICS)
    rows_num.append(f"          <tr><td>{E(m['name'])}</td>{cells}</tr>")
heads = "".join(f"<th>{E(label)}</th>" for _, label, _, _, _ in METRICS)
# a machine with fewer sessions than this (the Galaxy Book in the 0.3.0 baseline, whose GPU hung early in the night) is
# named in the note instead
FEW = 5
few = [m for m in MACHINES if m["alias"] in sessions and min(sessions[m["alias"]]) < FEW]
FEW_NOTE = "".join(f" {E(m['name'])}: {min(sessions[m['alias']])} sessions of each only, so its numbers are less sure." for m in few)
# machines of the lab without numbers in this baseline, and why
NODATA_NOTE = "".join(f" The {E(m['name'])} {E(m['nodata'])}." for m in MACHINES if not m["baseline"] and m.get("nodata"))

page = f"""{head("Hypoland: the lab", "The test machines Hypoland is measured on, from a 2006 Core 2 Duo laptop to a Snapdragon X Elite laptop, and every machine's numbers against stock Hyprland.", "The test machines Hypoland is measured on, and every machine's numbers against stock Hyprland.", "lab.html")}

<!-- Generated by scripts/web/lab.py from the hardware facts in it and the baseline's values, do not edit by hand. -->
{bar([("numbers", 2), ("method", 3)], "lab.html")}

<main class="desk" id="top">

  <section class="win full" aria-labelledby="t-machines">
    <h2 class="title" id="t-machines">lshw: the test machines</h2>
    <div class="body">
      <p>
        Hypoland is measured on real machines, each with Omarchy installed and its full session running, reached over
        ssh from one desktop. The X200 is the target; the others make sure that what helps it costs nothing
        on the GPUs and drivers people actually have.
      </p>
      <div class="scroll"><table>
        <thead><tr><th>Machine</th><th>Year</th><th>CPU</th><th>GPU, Mesa driver</th><th>Screen</th><th>RAM</th><th>What it stands for</th></tr></thead>
        <tbody>
{chr(10).join(rows_hw)}
        </tbody>
      </table></div>
      <p class="note">
        {E(RETIRED)} Not in the lab: NVIDIA
        (<code>nouveau</code>), AMD's RDNA GPUs, and the two other Intel generations that stop at GLES 2.0, GMA X3100 (965GM) and Ironlake. Reports from any of them are welcome.
      </p>
    </div>
  </section>

  <section class="win full" id="numbers" aria-labelledby="t-numbers">
    <h2 class="title" id="t-numbers">bench: Hypoland against Hyprland {HYPRLAND}, per machine</h2>
    <div class="body">
      <div class="scroll"><table>
        <thead><tr><th>Hypoland / Hyprland {HYPRLAND}</th>{heads}</tr></thead>
        <tbody>
{chr(10).join(rows_num)}
        </tbody>
      </table></div>
      <p class="note">
        Compositor CPU in percent of one core; medians of {sessions_text(sessions.values(), FEW)} per machine,
        {RUN}. {TWO_NIGHTS}{FEW_NOTE}{NODATA_NOTE} Both ran without realtime scheduling (<code>HYPRLAND_NO_RT=1</code>,
        as Omarchy runs Hyprland), except on the Galaxy Book; Hyprland with
        <code>quirks:skip_non_kms_dmabuf_formats = false</code>, Hypoland's default, and on the X200 and the Turbo-X with
        Omarchy's GLES&nbsp;3 override (<a href="https://github.com/omacom/omarchy/pull/14764">omarchy#14764</a>), without
        which it does not start there. Green: Hypoland at least 5% better; red: at least 5% worse. Frames are the
        compositor's page flips (the Galaxy Book runs at 120&nbsp;Hz; the Mac mini M1 reports none). Memory includes the
        shell's shared pages. The Turbo-X has no memory or Chromium cell: on its 1&nbsp;GB most of either compositor sits
        in swap, which the memory does not count, and Chromium opens no window there. More:
        <a href="terminals.html">terminals</a>, <a href="games.html">games</a>, <a href="files.html">file managers</a>, <a href="energy.html">energy</a>.
        {RAW}
      </p>
    </div>
  </section>

  <section class="win third" id="method" aria-labelledby="t-method">
    <h2 class="title" id="t-method">measure.sh: how it is measured</h2>
    <div class="body">
      <p>
        Every number comes from a fresh session: the machine's display manager is restarted, the desktop settles for
        a minute, then the benchmark runs its workloads with the compositor's real clients (foot, Alacritty, Chromium,
        GTK&nbsp;3 and 4, Qt&nbsp;Quick, Tk through Xwayland, Omarchy's shell). Keys and pointer motions come from a
        uinput device, the same path as a real keyboard. Latencies are the time from an input event to the first
        screen-capture frame that shows its effect. Two builds alternate through a night, so a drift of the machine
        hits both the same.
      </p>
    </div>
  </section>

  <section class="win third" aria-labelledby="t-tools">
    <h2 class="title" id="t-tools">perf: what else is looked at</h2>
    <div class="body">
      <ul class="pixel-list">
        <li>GPU time per frame, by the compositor's own pass profile</li>
        <li>Power, by RAPL or the battery's discharge rate, net of an idle baseline</li>
        <li>Memory: PSS, heap, threads and the GPU buffers the compositor holds</li>
        <li>Profiles with <code>perf</code> and the kernel's and Mesa's symbols</li>
        <li>Every machine's journal and kernel log stream to the desktop, so a machine that dies leaves its last words</li>
      </ul>
    </div>
  </section>

  <section class="win third" aria-labelledby="t-data">
    <h2 class="title" id="t-data">ls docs/baseline: the data</h2>
    <div class="body">
      <ul class="pixel-list">
        <li><a href="https://github.com/hegjon/hypoland/tree/master/docs/baseline">docs/baseline</a>: every comparison with stock Hyprland, with the raw values and the scripts that made them</li>
        <li><a href="https://github.com/hegjon/hypoland/tree/master/scripts/bench">scripts/bench</a>: the benchmark, its workloads and clients</li>
        <li><a href="https://github.com/hegjon/hypoland/tree/master/docs/notes">docs/notes</a>: the engineering notes, with what was tried, measured and dropped</li>
        <li><a href="https://github.com/hegjon/hypoland/blob/master/CHANGELOG.md">CHANGELOG.md</a>: the changes per release with their measured effect</li>
      </ul>
    </div>
  </section>

</main>

{FOOTER}
"""
open(OUT, "w").write(page)
print(f"wrote {OUT}: {len(rows_hw)} machines, {len(rows_num)} with numbers, {sessions_text(sessions.values(), FEW)}")
